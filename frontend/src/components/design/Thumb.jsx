const FILL = { a: 'url(#thumb-grad)', b: 'var(--thumb-box)', t: 'var(--thumb-line)', s: 'var(--thumb-strong)' };

export function Thumb({ section, layout }) {
  const shapes = T[section]?.[layout] || [];
  return (
    <svg viewBox="0 0 120 76" className="thumb" aria-hidden="true">
      <defs>
        <linearGradient id="thumb-grad" x1="0" y1="0" x2="1" y2="1">
          <stop offset="0" stopColor="var(--c1)" />
          <stop offset="0.55" stopColor="var(--c2)" />
          <stop offset="1" stopColor="var(--c3)" />
        </linearGradient>
      </defs>
      {shapes.map((sh, i) => {
        if (sh[0] === 'c') {
          const [, cx, cy, r, tone] = sh;
          return <circle key={i} cx={cx} cy={cy} r={r} fill={FILL[tone]} />;
        }
        const [tone, x, y, w, h, rx = 1.5] = sh;
        if (tone === 'o') {
          return <rect key={i} x={x} y={y} width={w} height={h} rx={rx} fill="none" stroke="url(#thumb-grad)" strokeWidth="1.5" />;
        }
        return <rect key={i} x={x} y={y} width={w} height={h} rx={rx} fill={FILL[tone]} />;
      })}
    </svg>
  );
}
